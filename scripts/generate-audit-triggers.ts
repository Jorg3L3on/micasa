/**
 * Writes the audit trigger SQL generated from `src/lib/server/audit/audited-models.ts`.
 *
 *   npm run generate:audit-triggers -- <migration_name>
 *     New migration prisma/migrations/<timestamp>_<name>/migration.sql with
 *     audit.row_change(), the append-only guards and one trigger per audited
 *     model (CREATE OR REPLACE / DROP IF EXISTS, so it is safe to re-run).
 *
 *   npm run generate:audit-triggers -- --append prisma/migrations/<dir>
 *     Appends the same SQL to an existing migration (e.g. one made with
 *     `prisma migrate dev --create-only`).
 *
 *   npm run generate:audit-triggers -- --stdout
 *
 * Pass --drop <Model>[,<Model>] to also drop triggers of models removed from the list.
 */
import { appendFileSync, mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { AUDIT_FUNCTIONS_SQL, auditTriggersSql, dropAuditTriggerSql } from '../src/lib/server/audit/audit-sql'

const args = process.argv.slice(2)
const flag = (name: string) => {
  const i = args.indexOf(name)
  return i === -1 ? undefined : (args[i + 1] ?? '')
}

const drops = (flag('--drop') ?? '').split(',').filter(Boolean)

const sql = [
  '-- Generated by scripts/generate-audit-triggers.ts from src/lib/server/audit/audited-models.ts.',
  '-- Do not edit by hand: change the config and regenerate.',
  '',
  AUDIT_FUNCTIONS_SQL,
  '',
  ...drops.map(dropAuditTriggerSql),
  auditTriggersSql(),
  '',
].join('\n')

const timestamp = () => new Date().toISOString().replace(/[-:T]/g, '').slice(0, 14)

if (args.includes('--stdout')) {
  process.stdout.write(sql)
} else if (flag('--append')) {
  const file = path.join(flag('--append')!, 'migration.sql')
  appendFileSync(file, `\n${sql}`)
  console.log(`appended audit SQL to ${file}`)
} else {
  const name = args.find((a) => !a.startsWith('--'))
  if (!name || !/^[a-z0-9_]+$/.test(name)) {
    console.error('usage: generate-audit-triggers <migration_name> | --append <dir> | --stdout')
    process.exit(1)
  }
  const dir = path.join('prisma/migrations', `${timestamp()}_${name}`)
  mkdirSync(dir, { recursive: true })
  writeFileSync(path.join(dir, 'migration.sql'), sql)
  console.log(`wrote ${dir}/migration.sql`)
}
