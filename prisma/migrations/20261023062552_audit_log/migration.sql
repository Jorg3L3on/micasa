         AND jsonb_typeof(to_jsonb(NEW) -> v_col) <> 'null' THEN
        RAISE EXCEPTION '% is append-only', TG_TABLE_NAME;
      END IF;
    END LOOP;
    RETURN NEW;
  END IF;
  RAISE EXCEPTION '% is append-only', TG_TABLE_NAME;
END
